"""Linux discovery sources [DESIGNED, NOT YET VERIFIED — decision D12 / ARCHITECTURE §6, §14].

Nothing in this module has run against a real Linux KiCad yet; every rule below is unit-tested
with a fake `System` (tests/test_installation.py) and must be re-validated by the Phase 0 Linux
spike on a GitHub-hosted runner before Linux enters the certified matrix. Sources, in contract
order:

- Distro packages (apt/dnf): `/usr/bin/kicad-cli` + `/usr/share/kicad`; `/usr/local` for a
  `make install`; `/opt/kicad*/bin/kicad-cli` for tarball/PPA-style prefixes. The SWIG `pcbnew`
  module lives in the system interpreter's site-packages, so `python` is `<prefix>/bin/python3`.
- Flatpak `org.kicad.KiCad`: detected with `flatpak list --app --columns=application`. There is no
  host-side kicad-cli binary, so kiwrap generates a POSIX-sh wrapper under
  `<storage_home>/flatpak/org.kicad.KiCad/kicad-cli` that runs
  `flatpak run --command=kicad-cli org.kicad.KiCad "$@"` and forwards the `KICAD_*_HOME` variables
  into the sandbox (`flatpak run` does not inherit them); a `python3` wrapper is generated the same
  way. `share` points at the host-side deployment (`/var/lib/flatpak/app/.../files/share/kicad` or
  the per-user equivalent) when it exists.
- Snap: `/snap/bin/kicad.kicad-cli`, share under `/snap/kicad/current/usr/share/kicad`.
- AppImage on PATH (`*kicad*.AppImage`): NEVER executed directly (the AppImage entry point is the
  GUI). It is unpacked once with `--appimage-extract` into `<storage_home>/appimage/<name>/`, and
  the unpacked `squashfs-root/usr/bin/kicad-cli` is the candidate.
"""

from __future__ import annotations

import re
from pathlib import Path

from kiwrap.platform import Platform
from kiwrap.platform.discovery import Candidate, prefix_candidate
from kiwrap.platform.system import System

FLATPAK_ID = "org.kicad.KiCad"
DISTRO_PREFIXES = (Path("/usr"), Path("/usr/local"))
OPT_GLOB = "kicad*"
SNAP_CLI = Path("/snap/bin/kicad.kicad-cli")
SNAP_ROOT = Path("/snap/kicad/current")
FORWARDED_ENV = (
    "KICAD_CONFIG_HOME",
    "KICAD_DOCUMENTS_HOME",
    "KICAD_CACHE_HOME",
    "KICAD_API_SOCKET",
    "KICAD_API_TOKEN",
)
_APPIMAGE_RE = re.compile(r"kicad.*\.appimage$", re.IGNORECASE)


def distro_candidates(platform: Platform, system: System) -> list[Candidate]:
    out: list[Candidate] = []
    prefixes = list(DISTRO_PREFIXES) + [p for p in system.glob(Path("/opt"), OPT_GLOB) if system.is_dir(p)]
    for prefix in prefixes:
        kicad_cli = prefix / "bin" / platform.kicad_cli_name()
        if system.is_file(kicad_cli):
            out.append(prefix_candidate(prefix, kicad_cli, "apt", platform, system, prefix=str(prefix)))
    return out


def flatpak_wrapper_script(command: str, app_id: str = FLATPAK_ID) -> str:
    """POSIX sh wrapper. `${VAR:+"--env=VAR=$VAR"}` expands to exactly one argument when VAR is
    set and to nothing otherwise, so paths with spaces survive. `--filesystem=host` lets kicad-cli
    inside the sandbox reach project files outside $HOME."""
    forwards = "\n".join(f'  ${{{v}:+"--env={v}=${v}"}} \\' for v in FORWARDED_ENV)
    return (
        "#!/bin/sh\n"
        f"# Generated by kiwrap: runs {command} inside the {app_id} Flatpak with kiwrap's environment.\n"
        "exec flatpak run --filesystem=host \\\n"
        f"{forwards}\n"
        f'  --command={command} {app_id} "$@"\n'
    )


def flatpak_installed(system: System, app_id: str = FLATPAK_ID) -> bool:
    if system.which("flatpak") is None:
        return False
    result = system.run(
        ["flatpak", "list", "--app", "--columns=application"], env=system.environ(), timeout_s=30
    )
    return result.ok and app_id in {line.strip() for line in result.stdout.splitlines()}


def flatpak_candidates(
    platform: Platform, system: System, storage_home: Path, app_id: str = FLATPAK_ID
) -> list[Candidate]:
    if platform.is_windows or not flatpak_installed(system, app_id):
        return []
    wrapper_dir = storage_home / "flatpak" / app_id
    kicad_cli = wrapper_dir / platform.kicad_cli_name()
    python = wrapper_dir / "python3"
    system.write_text(kicad_cli, flatpak_wrapper_script("kicad-cli", app_id), executable=True)
    system.write_text(python, flatpak_wrapper_script("python3", app_id), executable=True)
    deployments = (
        Path("/var/lib/flatpak/app") / app_id / "current" / "active" / "files",
        system.home() / ".local" / "share" / "flatpak" / "app" / app_id / "current" / "active" / "files",
    )
    root = next((d for d in deployments if system.is_dir(d / "share" / "kicad")), wrapper_dir)
    return [
        Candidate(root, kicad_cli, root / "share" / "kicad", "flatpak", python, None, {"flatpak_id": app_id})
    ]


def snap_candidates(platform: Platform, system: System) -> list[Candidate]:
    if not system.is_file(SNAP_CLI):
        return []
    share = SNAP_ROOT / "usr" / "share" / "kicad"
    python = SNAP_ROOT / "usr" / "bin" / "python3"
    return [
        Candidate(
            SNAP_ROOT,
            SNAP_CLI,
            share,
            "snap",
            python if system.is_file(python) else None,
            None,
            {"snap": "kicad"},
        )
    ]


def appimage_candidates(platform: Platform, system: System, storage_home: Path) -> list[Candidate]:
    out: list[Candidate] = []
    for entry in system.path_entries():
        for file in system.listdir(entry):
            if not _APPIMAGE_RE.search(file.name) or not system.is_file(file):
                continue
            extract_dir = storage_home / "appimage" / file.name
            root = extract_dir / "squashfs-root" / "usr"
            kicad_cli = root / "bin" / platform.kicad_cli_name()
            if not system.is_file(kicad_cli):
                system.mkdir(extract_dir)
                result = system.run(
                    [str(file), "--appimage-extract"], env=system.environ(), timeout_s=600, cwd=extract_dir
                )
                if not result.ok or not system.is_file(kicad_cli):
                    continue
            out.append(prefix_candidate(root, kicad_cli, "appimage", platform, system, appimage=str(file)))
    return out


def linux_candidates(platform: Platform, system: System, storage_home: Path) -> list[Candidate]:
    return (
        distro_candidates(platform, system)
        + flatpak_candidates(platform, system, storage_home)
        + snap_candidates(platform, system)
        + appimage_candidates(platform, system, storage_home)
    )
